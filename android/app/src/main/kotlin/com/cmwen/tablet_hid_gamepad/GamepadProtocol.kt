package com.cmwen.tablet_hid_gamepad

/** Report 1: buttons including digital LT/RT, hat, unsigned centered XY/ZRz. */
object GamepadProtocol {
    const val REPORT_ID = 1
    const val BODY_SIZE = 11
    const val REPORT_SIZE = 12
    val DESCRIPTOR = intArrayOf(
        0x05,0x01,0x09,0x05,0xA1,0x01,0x85,0x01,
        0x05,0x09,0x19,0x01,0x29,0x10,0x15,0x00,0x25,0x01,0x75,0x01,0x95,0x10,0x81,0x02,
        0x05,0x01,0x09,0x39,0x15,0x00,0x25,0x07,0x35,0x00,0x46,0x3B,0x01,0x65,0x14,0x75,0x04,0x95,0x01,0x81,0x42,
        0x65,0x00,0x75,0x04,0x95,0x01,0x81,0x03,
        0x09,0x30,0x09,0x31,0x09,0x32,0x09,0x35,0x15,0x00,0x27,0xFF,0xFF,0x00,0x00,0x35,0x00,0x47,0xFF,0xFF,0x00,0x00,0x75,0x10,0x95,0x04,0x81,0x02,0xC0
    ).map { it.toByte() }.toByteArray()
    val activeDescriptor get() = DESCRIPTOR
    fun allUp() = ByteArray(BODY_SIZE).apply {
        this[2] = 8
        for (offset in intArrayOf(4, 6, 8, 10)) this[offset] = 0x80.toByte()
    }
}
